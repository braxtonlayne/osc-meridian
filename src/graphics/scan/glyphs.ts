function parseStroke(src: string): GlyphPoint[] {
  const pts: GlyphPoint[] = [];
  for (const pair of src.trim().split(/\s+/)) {
    const [xs, ys] = pair.split(',');
    const x = Number(xs);
    const y = Number(ys);
    const prev = pts[pts.length - 1];
    if (prev && prev.x === x && prev.y === y) prev.corner = true;
    else pts.push({ x, y });
  }
  return pts;
}

