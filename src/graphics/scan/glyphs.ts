/**
 * Hand-authored single-stroke alphabet.
 *
 * Coordinate system (glyph units, y UP): baseline y = 0, x-height 10, cap
 * height 16, ascender 17, descender -7. Each glyph is one or more pen strokes
 * separated by `|`; a stroke is a list of `x,y` points the pen passes through.
 * Points are joined with a smooth curve. Writing the same point twice in a row
 * marks a hard corner (the pen changes direction without lifting).
 *
 * This is stroke data, not a font: the pen engine (pen.ts) perturbs every
 * point, slants, wobbles and gives the line a varying width per hand.
 */

export interface GlyphPoint {
  x: number;
  y: number;
  /** Hard corner: the curve is broken here. */
  corner?: boolean;
}

export interface Glyph {
  /** Advance width in glyph units. */
  w: number;
  strokes: GlyphPoint[][];
}

