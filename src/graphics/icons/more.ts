const speaker16 = (): Cv => {
  const t = new Cv(16);
  t.r(1, 6, 3, 4, 'g');
  for (let i = 0; i <= 4; i++) t.v(4 + i, 6 - i, 4 + 2 * i, 'g');
  return t.ol('k').bev('g', 'h', 's');
};

const speaker32 = (): Cv => {
  const t = new Cv(32);
  t.r(2, 12, 6, 8, 'g');
  for (let i = 0; i <= 8; i++) t.v(8 + i, 12 - i, 8 + 2 * i, 'g');
  return t.ol('k').bev('g', 'h', 's');
};

const tickShape = (n: 16 | 32): Cv => {
  const t = new Cv(n);
  if (n === 16) {
    for (let i = 0; i <= 3; i++) t.r(1 + i, 7 + i, 3, 4, 'v');
    for (let i = 0; i <= 7; i++) t.r(5 + i, 10 - i, 3, 4, 'v');
  } else {
    for (let i = 0; i <= 7; i++) t.r(3 + i, 14 + i, 5, 7, 'v');
    for (let i = 0; i <= 15; i++) t.r(11 + i, 21 - i, 5, 7, 'v');
  }
  return t.ol('k');
};

